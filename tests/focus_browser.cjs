// Optional development QA: npm install --no-save playwright, then start serve_focus_fixture.py.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{})});
  const errors=[];
  const context=await browser.newContext({viewport:{width:393,height:852},deviceScaleFactor:2,isMobile:true,hasTouch:true});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8879/phone');
  await page.waitForFunction(()=>window.OrbitClient?.state?.profile?.length===48);
  await page.locator('[data-quick=activity]').click();
  await page.waitForFunction(()=>window.OrbitClient.state.events.some(e=>e.kind==='activity'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'No horizontal phone overflow');
  const stat=await page.evaluate(()=>({events:OrbitClient.state.events.length,cloud:OrbitClient.state.aiEnabled}));
  assert.equal(stat.cloud,false);
  const shots=path.join(__dirname,'..','docs','previews');fs.mkdirSync(shots,{recursive:true});
  await page.goto('http://127.0.0.1:8879/phone?demo=1');
  await page.waitForFunction(()=>window.OrbitClient?.state?.demo);
  await page.screenshot({path:path.join(shots,'pocket-v2-demo.png'),fullPage:false});
  await page.goto('http://127.0.0.1:8879/phone');
  await page.waitForFunction(()=>window.OrbitClient?.state);
  await page.locator('[data-tab=focus]').click();
  await page.locator('.candidate').first().click();
  await page.locator('#habit').fill('Notice lunch and tag my activity');
  await page.locator('#focus-form .primary').click();
  await page.waitForFunction(()=>!!OrbitClient.state.focus);
  await page.locator('#active-focus .checkin-buttons button').first().click();
  await page.waitForFunction(()=>OrbitClient.state.focus.doneDays===1);
  await page.locator('[data-tab=food]').click();
  await page.locator('#portion-weight').fill('150');
  await page.locator('#carbs-density').fill('28');
  assert.equal(await page.locator('#label-result').textContent(),'42.0 g carbohydrate');
  await page.locator('#use-label').click();
  assert.equal(await page.locator('#confirmed-carbs').inputValue(),'42.0');
  assert.equal(await page.locator('#carbs-checked').isChecked(),false);
  await page.locator('#carbs-checked').check();
  await page.locator('#food-note').fill('Label checked · rice');
  await page.locator('#food-save .primary').click();
  await page.waitForFunction(()=>OrbitClient.state.events.some(e=>e.kind==='food'&&e.carbs===42));
  const display=await browser.newPage({viewport:{width:800,height:800},deviceScaleFactor:2});
  display.on('pageerror',e=>errors.push(e.message));
  await display.goto('http://127.0.0.1:8879/rhythm');
  await display.waitForFunction(()=>!!OrbitClient.state.focus);
  assert(await display.evaluate(()=>OrbitClient.state.events.some(e=>e.kind==='activity')),'Shared events appear in round data');
  await display.locator('[data-mode=days]').click();
  await display.mouse.move(675,400);
  await display.waitForFunction(()=>document.querySelector('#centre-title').textContent.includes('in range'));
  await display.mouse.move(400,400);
  await display.locator('[data-mode=rhythm]').click();
  await display.mouse.move(400,400);
  await display.goto('http://127.0.0.1:8879/rhythm?demo=1');
  await display.waitForFunction(()=>OrbitClient.state?.demo);
  await display.screenshot({path:path.join(shots,'rhythm-v2-demo.png')});
  assert.deepEqual(errors,[]);
  console.log('PASS: phone tags, focus, check-in, label calculator, food log, shared round state, ring hover, phone overflow, screenshots.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
